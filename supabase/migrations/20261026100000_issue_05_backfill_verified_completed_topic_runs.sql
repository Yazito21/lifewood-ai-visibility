-- Recover only completed topic runs whose persisted data and stage journal prove completeness.
create temporary table issue05_verified_topic_runs on commit drop as
with stage_topic as (
  select tr.id, tr.project_id, tr.provider, tr.tracking_location,
         (tr.started_at at time zone 'Asia/Kuala_Lumpur')::date as metric_date,
         st.metadata->>'topic' as topic, tr.started_at, tr.completed_at,
         tr.total_prompts, tr.completed_prompts, tr.status,
         row_number() over (
           partition by tr.project_id, (tr.started_at at time zone 'Asia/Kuala_Lumpur')::date,
                        st.metadata->>'topic', tr.provider, tr.tracking_location
           order by tr.completed_at desc nulls last, tr.id desc
         ) as rn
  from public.tracking_runs tr
  join public.tracking_run_stages st on st.run_id=tr.id and st.stage_key='topic_cleanup'
  where tr.topic is null and tr.status='completed' and tr.completed_at is not null
    and tr.published_at is null and tr.total_prompts=tr.completed_prompts
    and st.status='completed' and st.metadata->>'topic' in ('Skin','Mind','Longevity')
    and st.metadata->>'topic_scoped'='true'
), stage_valid as (
  select s.* from stage_topic s
  where s.rn=1
    and (select count(*) from public.tracking_run_stages x where x.run_id=s.id)>0
    and not exists(select 1 from public.tracking_run_stages x where x.run_id=s.id and x.status<>'completed')
    and (select count(*) from public.ai_responses ar where ar.run_id=s.id and ar.response_status='completed')=s.completed_prompts
    and (select count(*) from public.ai_responses ar where ar.run_id=s.id)=s.total_prompts
    and (select count(distinct o.brand_id) from public.topic_brand_observations o
         where o.project_id=s.project_id and o.metric_date=s.metric_date and o.topic=s.topic
           and o.llm_provider=s.provider and o.tracking_location=s.tracking_location
           and o.run_id is null)
        = (select count(*) from public.topic_brand_assignments a
           where a.project_id=s.project_id and a.topic=s.topic and a.role='competitor' and a.include_in_metrics=true)
    and (select count(*) from public.topic_brand_observations o
         where o.project_id=s.project_id and o.metric_date=s.metric_date and o.topic=s.topic
           and o.llm_provider=s.provider and o.tracking_location=s.tracking_location and o.run_id is null)
        = (select count(*) from public.topic_brand_assignments a
           where a.project_id=s.project_id and a.topic=s.topic and a.role='competitor' and a.include_in_metrics=true)
)
select id as run_id, project_id, metric_date, topic, provider, tracking_location, completed_at
from stage_valid;

-- Correct the topic dimension from the completed topic-cleanup stage journal.
update public.tracking_runs tr
set topic=c.topic
from issue05_verified_topic_runs c
where tr.id=c.run_id and tr.topic is null;

-- Attach lineage to the exact existing daily observation slice; do not synthesize observations.
update public.topic_brand_observations o
set run_id=c.run_id
from issue05_verified_topic_runs c
where o.project_id=c.project_id and o.metric_date=c.metric_date and o.topic=c.topic
  and o.llm_provider=c.provider and o.tracking_location=c.tracking_location
  and o.run_id is null;

-- Restore lineage on the daily metric rows generated by the same verified run.
update public.visibility_daily v
set run_id=c.run_id
from issue05_verified_topic_runs c
where v.project_id=c.project_id and v.metric_date=c.metric_date and v.topic=c.topic
  and v.tracking_location=c.tracking_location and v.run_id is null
  and v.llm_provider in ('chatgpt','Overall');

-- Publish only after the observation set has been attached and still matches the registered eligible population.
update public.tracking_runs tr
set published_at=c.completed_at
from issue05_verified_topic_runs c
where tr.id=c.run_id and tr.status='completed' and tr.published_at is null
  and (select count(distinct o.brand_id) from public.topic_brand_observations o
       where o.run_id=tr.id and o.project_id=tr.project_id and o.metric_date=c.metric_date
         and o.topic=c.topic and o.llm_provider=tr.provider and o.tracking_location=tr.tracking_location)
      = (select count(*) from public.topic_brand_assignments a
         where a.project_id=tr.project_id and a.topic=c.topic and a.role='competitor' and a.include_in_metrics=true);
